def demo_card(painter: Painter, step, max_lines=13):
    p, g = painter, []
    command = step["command"].replace("\\n", " ⏎ ")
    lines = step["output"].splitlines()
    shown = lines[:max_lines]
    truncated = len(lines) > max_lines
    w = 780
    bar_h, pad = 40, 18
    h = bar_h + pad + 24 + (len(shown) + (2 if truncated else 1)) * 20 + pad
    g.append(p.rect(0, 0, w, h, fill="code", stroke="line", rx=12, sw=1))
    for i, dot in enumerate((12, 30, 48)):
        g.append(p.circle(dot, bar_h / 2, 4.5, "muted", stroke="code", sw=0))
    g.append(p.txt(70, bar_h / 2 + 4, local(step["label"]), 12, "muted", mono=True))
    g.append(p.line(0, bar_h, w, bar_h, color="line", sw=1))
    y = bar_h + pad + 14
    g.append(p.txt(pad, y, "$ " + command, 12.5, "primary", mono=True))
    y += 24
    for line in shown:
        color = "ink"
        if "✓" in line or "揭晓" in line:
            color = "secondary"
        g.append(p.txt(pad + 12, y, line[:92], 12, color, mono=True, weight=600
                       if color == "secondary" else 400))
        y += 20
    if truncated:
        g.append(p.txt(pad + 12, y, f"……（其余 {len(lines) - max_lines} 行见"
                                    f" docs/demo-results.json）", 11.5, "muted", mono=True))
    return w, h, "".join(g)


