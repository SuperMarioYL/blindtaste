# 装饰性动画：只做漂浮 / 透明度呼吸 / 虚线流动；reduced-motion 下全部停用，
# 静态帧仍然完整（所有标签、关系、结果都在）。
ANIMATION_CSS = """
.bt-float-a { animation: bt-float-a 7s ease-in-out infinite alternate; }
.bt-float-b { animation: bt-float-b 9s ease-in-out infinite alternate; }
.bt-breathe { animation: bt-breathe 4.5s ease-in-out infinite; }
.bt-dash { stroke-dasharray: 6 5; animation: bt-dash 2.6s linear infinite; }
@keyframes bt-float-a { from { transform: translate(0px, 0px); } to { transform: translate(6px, -9px); } }
@keyframes bt-float-b { from { transform: translate(0px, 0px); } to { transform: translate(-8px, 7px); } }
@keyframes bt-breathe { 0%, 100% { opacity: .35; } 50% { opacity: 1; } }
@keyframes bt-dash { to { stroke-dashoffset: -22; } }
@media (prefers-reduced-motion: reduce) {
  .bt-float-a, .bt-float-b, .bt-breathe, .bt-dash { animation: none; }
}
"""


def local(value):
    """zh 为主（本项目主语言），en 兜底。"""
    if isinstance(value, dict):
        return str(value.get("zh") or value.get("en") or "")
    return str(value or "")


def wrap(text, width):
    return textwrap.wrap(text, width=width) or [""]


class Painter:
    """一个主题（light/dark）下的 SVG 元素构造器。"""

    def __init__(self, mode, palette):
        self.mode = mode
        self.p = palette[mode]

    def txt(self, x, y, s, size=14, color="ink", anchor="start",
            weight=400, mono=False, opacity=None):
        extra = f" opacity='{opacity}'" if opacity is not None else ""
        return (
            f"<text x='{x}' y='{y}' fill='{self.p[color]}' font-size='{size}'"
            f" text-anchor='{anchor}' font-weight='{weight}'"
            f" font-family=\"{MONO if mono else SANS}\"{extra}>"
            f"{escape(local(s))}</text>"
        )

    def para(self, x, y, s, width_chars, size=13, color="muted", lh=1.5,
             limit=3, mono=False):
        rows = wrap(local(s), width_chars)[:limit]
        if len(wrap(local(s), width_chars)) > limit:
            rows[-1] = rows[-1].rstrip("。.") + "…"
        return "".join(
            self.txt(x, y + i * size * lh, r, size, color, mono=mono)
            for i, r in enumerate(rows)
        )

    def rect(self, x, y, w, h, fill="panel", stroke="line", rx=12,
             sw=1.2, dashed=False, opacity=None):
        extra = f" opacity='{opacity}'" if opacity is not None else ""
        dash = " stroke-dasharray='5 4'" if dashed else ""
        return (
            f"<rect x='{x}' y='{y}' width='{w}' height='{h}' rx='{rx}'"
            f" fill='{self.p[fill]}' stroke='{self.p[stroke]}'"
            f" stroke-width='{sw}'{dash}{extra}/>"
        )

    def circle(self, cx, cy, r, fill, stroke="line", sw=1.2, opacity=None,
               cls=None):
        extra = f" opacity='{opacity}'" if opacity is not None else ""
        klass = f" class='{cls}'" if cls else ""
        return (
            f"<circle cx='{cx}' cy='{cy}' r='{r}' fill='{self.p[fill]}'"
            f" stroke='{self.p[stroke]}' stroke-width='{sw}'{klass}{extra}/>"
        )

    def line(self, x1, y1, x2, y2, color="line", sw=1.1, opacity=None,
             cls=None, dasharray=None):
        extra = f" opacity='{opacity}'" if opacity is not None else ""
        klass = f" class='{cls}'" if cls else ""
        dash = f" stroke-dasharray='{dasharray}'" if dasharray else ""
        return (
            f"<line x1='{x1}' y1='{y1}' x2='{x2}' y2='{y2}'"
            f" stroke='{self.p[color]}' stroke-width='{sw}'{dash}{klass}{extra}/>"
        )

    def arrow(self, x1, y1, x2, y2, color="muted", cls="bt-dash"):
        """带箭头的连线（虚线流动表现数据在走）。"""
        head = 6
        ang = math.atan2(y2 - y1, x2 - x1)
        bx, by = x2 - head * math.cos(ang), y2 - head * math.sin(ang)
        left = (
            bx - 4 * math.cos(ang - math.pi / 2),
            by - 4 * math.sin(ang - math.pi / 2),
        )
        right = (
            bx + 4 * math.cos(ang - math.pi / 2),
            by + 4 * math.sin(ang - math.pi / 2),
        )
        pts = f"{x2},{y2} {left[0]:.1f},{left[1]:.1f} {right[0]:.1f},{right[1]:.1f}"
        return (
            self.line(x1, y1, x2, y2, color=color, cls=cls)
            + f"<polygon points='{pts}' fill='{self.p[color]}'/>"
        )

    def grid(self, w, h, step=48):
        out = []
        for x in range(step, w, step):
            out.append(self.line(x, 0, x, h, color="line", sw=0.6, opacity=0.45))
        for y in range(step, h, step):
            out.append(self.line(0, y, w, y, color="line", sw=0.6, opacity=0.45))
        return "".join(out)

    def chip(self, x, y, w, text, color="secondary", size=12.5, h=26):
        return (
            self.rect(x, y, w, h, fill="bg", stroke=color, rx=13, sw=1.1)
            + self.txt(x + w / 2, y + h / 2 + size * 0.36, text, size, color,
                       anchor="middle")
        )


def svg_document(slug, w, h, title, desc, body, palette_id, bg, animated=True):
    style = f"<style>{ANIMATION_CSS}</style>" if animated else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}"'
        f' viewBox="0 0 {w} {h}" data-palette="{palette_id}" role="img"'
        f' aria-labelledby="{slug}-title {slug}-desc">'
        f'<title id="{slug}-title">{escape(title)}</title>'
        f'<desc id="{slug}-desc">{escape(desc)}</desc>{style}'
        f'<rect width="{w}" height="{h}" fill="{bg}"/>{body}</svg>\n'
    )


