"""Construct README/website SVG artwork from authored facts and the renderer palette.

Reads docs/presentation.json (authored facts), web/palette.json (generated by
the pinned web-factory renderer from web/site.json) and docs/demo-results.json
(the recorded demo run), then writes to assets/presentation/ and
web/assets/presentation/:

- the four animated light/dark SVG groups — hero, architecture, process,
  integrations — in desktop and mobile compositions, each with a fully static
  variant (no animation at all) for reduced-motion picture sources;
- the demo step terminal cards, whose command and output lines come verbatim
  from docs/demo-results.json — nothing here is invented.

Every SVG is self-contained (no script, no remote references), carries the
palette id in data-palette, and keeps a complete static frame: labels,
relationships and results survive with animations off.
"""

